package fOne.builder;

public class FormulaOneCar {
    String team;
    String engine;
    int horsepower;
    double weight;
    int yearModel;

    public FormulaOneCar(String team, String engine, int horsepower, double weight, int yearModel) {
        this.team = team;
        this.engine = engine;
        this.horsepower = horsepower;
        this.weight = weight;
        this.yearModel = yearModel;
    }
}
